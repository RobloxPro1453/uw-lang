//! `slots.lock`: the slot number every object field (`var agent.stamina`) got, kept between builds.
//!
//! A saved game stores slot values by number, so a field must keep its number for ever (meclis
//! "maden" KARAR §2): the lock only grows. A new field gets the next number above both the kit's
//! own `slot_<kind>_*` constants and every number already in the lock; a field that is no longer
//! declared keeps its line (its number is never given to another field) and the build warns.
//!
//! The file is plain TOML, one table per kind, sorted, so it diffs cleanly:
//!
//! ```toml
//! [agent]
//! stamina = 34
//! ```

use std::collections::BTreeMap;

/// The slot numbers given out so far, per kind and field name.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SlotLock {
    kinds: BTreeMap<String, BTreeMap<String, i64>>,
}

impl SlotLock {
    /// An empty lock (a project that has never been built).
    pub fn new() -> SlotLock {
        SlotLock::default()
    }

    /// Reads `slots.lock` text. Every value must be a whole number and no two fields of one kind
    /// may share a number (that would mean two fields write the same saved value).
    pub fn parse(text: &str) -> Result<SlotLock, String> {
        let table: toml::Table = text.parse().map_err(|e| format!("slots.lock: {e}"))?;
        let mut lock = SlotLock::new();
        for (kind, fields) in table {
            let toml::Value::Table(fields) = fields else {
                return Err(format!("slots.lock: `{kind}` must be a table of `field = slot` lines"));
            };
            let mut seen: BTreeMap<i64, String> = BTreeMap::new();
            for (name, value) in fields {
                let Some(slot) = value.as_integer() else {
                    return Err(format!("slots.lock: `{kind}.{name}` must be a slot number"));
                };
                if let Some(other) = seen.insert(slot, name.clone()) {
                    return Err(format!("slots.lock: `{kind}.{other}` and `{kind}.{name}` both have slot {slot}"));
                }
                lock.kinds.entry(kind.clone()).or_default().insert(name, slot);
            }
        }
        Ok(lock)
    }

    /// The text to write back: a header, then one sorted table per kind.
    pub fn to_text(&self) -> String {
        let mut out = String::from(
            "# GENERATED by uw: the slot number of every object field. Commit this file and never\n\
             # renumber it: saved games store field values by these numbers. A field you delete keeps\n\
             # its line so its number is not given to another field.\n",
        );
        for (kind, fields) in &self.kinds {
            out.push_str(&format!("\n[{kind}]\n"));
            for (name, slot) in fields {
                out.push_str(&format!("{name} = {slot}\n"));
            }
        }
        out
    }

    /// The locked slot of `kind.name`, if it was ever given one.
    pub fn get(&self, kind: &str, name: &str) -> Option<i64> {
        self.kinds.get(kind).and_then(|fields| fields.get(name)).copied()
    }

    /// The highest locked slot of a kind.
    pub fn highest(&self, kind: &str) -> Option<i64> {
        self.kinds.get(kind).and_then(|fields| fields.values().copied().max())
    }

    /// Records a newly given slot.
    pub(crate) fn insert(&mut self, kind: &str, name: &str, slot: i64) {
        self.kinds.entry(kind.to_owned()).or_default().insert(name.to_owned(), slot);
    }

    /// Every `(kind, name, slot)`, sorted by kind then name.
    pub fn fields(&self) -> impl Iterator<Item = (&str, &str, i64)> {
        self.kinds
            .iter()
            .flat_map(|(kind, fields)| fields.iter().map(move |(name, slot)| (kind.as_str(), name.as_str(), *slot)))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn text_round_trips_sorted() {
        let mut lock = SlotLock::new();
        lock.insert("troop", "rank", 40);
        lock.insert("agent", "stamina", 34);
        lock.insert("agent", "rage", 35);
        let text = lock.to_text();
        assert!(text.find("[agent]").unwrap() < text.find("[troop]").unwrap());
        assert!(text.find("rage = 35").unwrap() < text.find("stamina = 34").unwrap());
        assert_eq!(SlotLock::parse(&text).unwrap(), lock);
    }

    #[test]
    fn shared_number_and_bad_values_are_refused() {
        let err = SlotLock::parse("[agent]\na = 3\nb = 3\n").unwrap_err();
        assert!(err.contains("both have slot 3"), "{err}");
        assert!(SlotLock::parse("[agent]\na = \"x\"\n").is_err());
        assert!(SlotLock::parse("agent = 3\n").is_err());
    }
}
